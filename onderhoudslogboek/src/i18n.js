const dicts = { nl, en };

export function makeT(lang) {
  const d = dicts[lang] || nl;
  return (key, vars) => {
    let s = d[key] ?? nl[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
